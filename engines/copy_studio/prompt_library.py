# 各体裁默认包 (sub_genre 不在库中时回退)
_DEFAULT_KEYS = {
    GENRE_NOVEL: '现实主义',
    GENRE_SCRIPT: '都市情感',
    GENRE_AD_COPY: '产品卖点',
}


def get_style_pack(genre: str, sub_genre: str = '') -> Optional[Dict[str, Any]]:
    """取指定体裁+子类型的示例包. 子类型未收录 → 体裁默认包; 体裁未知 → None."""
    genre_packs = STYLE_PACKS.get(genre)
    if not genre_packs:
        return None
    if sub_genre and sub_genre in genre_packs:
        return genre_packs[sub_genre]
    return genre_packs.get(_DEFAULT_KEYS.get(genre, ''))


def build_style_block(genre: str, sub_genre: str = '', max_chars: int = 1500) -> str:
    """构造注入写章 prompt 的【写作示范库】文本块. 无可用包时返回 ''."""
    pack = get_style_pack(genre, sub_genre)
    if not pack:
        return ''
    lines = [f"【写作示范库 · {sub_genre or '通用'}】"]
    if pack.get('rules'):
        lines.append('写作规则:')
        lines += [f"- {r}" for r in pack['rules']]
    if pack.get('positive'):
        lines.append(f"✅ 正例示范 (模仿这种笔法的节奏与细节密度):\n{pack['positive']}")
    if pack.get('negative'):
        lines.append(f"❌ 反例示范 (对照避免这种空泛抒情/概念堆砌):\n{pack['negative']}")
    if pack.get('actions'):
        lines.append('叙事动作模板 (优先落实):')
        lines += [f"{i+1}. {a}" for i, a in enumerate(pack['actions'])]
    block = '\n'.join(lines)
    return block[:max_chars]



#!/usr/bin/env python3
"""MTSCOS 圆桌会议 orchestrator — 每天 02:00 + RunAtLoad 触发
   议题来源: mt_lab_task_hall 结案/审计/修复 DONE (近 7 天)
   输出: mt_roundtable_sessions (真实 11 列) + mt_ai_brain_feed_log
"""
import sys, json, sqlite3, datetime, hashlib, os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
DB = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "database", "app.db")

now = datetime.datetime.now()
now_s = now.strftime('%Y-%m-%d %H:%M:%S')

def _validate_payload(text):
    if not text: return False
    dangerous = ["DROP TABLE", "DROP DATABASE", ";--", "OR 1=", "UNION SELECT",
                 "<script", "javascript:", "eval(", "system(", "shell_exec(",
                 "__import__(", "pickle.loads", "subprocess.Popen"]
    low = text.lower()
    return not any(d.lower() in low for d in dangerous)

def main():
    # 1. 抽议题
    conn = sqlite3.connect(DB, timeout=15)
    c = conn.cursor()
    rows = c.execute("""SELECT id, title, verdict, hall_code, claim_owner, priority
        FROM mt_lab_task_hall WHERE status='DONE'
        AND (hall_code LIKE '%CLOSURE%' OR hall_code LIKE '%AUDIT%' OR hall_code LIKE '%REPORT%'
             OR hall_code LIKE '%SMOKE%' OR hall_code LIKE '%BRAIN_LOOP%' OR hall_code LIKE '%HARD%'
             OR hall_code LIKE '%SYNC%' OR hall_code LIKE '%ECOSYSTEM%')
        AND done_at > datetime('now','localtime','-7 days')
        ORDER BY done_at DESC LIMIT 10""").fetchall()
    if not rows:
        rows = c.execute("""SELECT id, title, verdict, hall_code, claim_owner, priority
            FROM mt_lab_task_hall WHERE status='DONE'
            ORDER BY done_at DESC LIMIT 5""").fetchall()
    print(f"[{now_s}] roundtable: {len(rows)} 议题", flush=True)
    if not rows:
        conn.close(); return 0

    # 2. 生成 session (真实 11 列)
    session_id = 'rt_' + hashlib.sha256((now_s + str([r[0] for r in rows])).encode()).hexdigest()[:16]
    agenda = json.dumps([{"id":r[0],"title":r[1][:50],"hc":r[3]} for r in rows], ensure_ascii=False)
    experts = json.dumps(["sys_roundtable_orchestrator","hall-closure-loop"], ensure_ascii=False)
    c.execute("""INSERT INTO mt_roundtable_sessions 
        (session_id, host_node, guest_node, agenda, summary, verdicts, action_items, brain_feed_ref, source_task_ids, status, session_at)
        VALUES (?,?,?,?,?,?,?,?,?,?,?)""",
        (session_id, "hall-closure-daemon", ",".join([(r[4] or "auto") for r in rows[:3]]),
         agenda, "", "AI-generated by roundtable_orchestrator", "", "", "", "DONE", now_s))
    sid = c.lastrowid
    conn.commit()

    # 3. feed brain_feed (validate first)
    if _validate_payload(agenda):
        c.execute("""INSERT INTO mt_ai_brain_feed_log 
        (session_id, feed_type, category, source, session_id, symbol, content, score, is_correct, extra, created_at, brain_marked)
        VALUES (?,?,?,?,?,?,?,?,?,?,?,?)""",
                  (sid, "roundtable", "", "roundtable_orchestrator", sid, "", agenda, 0, 1, "", now_s, 0))
        bid = c.lastrowid
        conn.commit()
    else:
        print(f"[{now_s}] roundtable: agenda 危险片段, 跳过 brain_feed", flush=True)
    conn.close()
    print(f"[{now_s}] roundtable: session #{sid} brain_feed #{bid} ✅", flush=True)
    return 0

if __name__ == '__main__':
    sys.exit(main())

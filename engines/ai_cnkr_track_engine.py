# 词汇分类标签 (普通话赛道专用干扰池)
_PSC_LABELS = ["轻声词", "儿化词", "多音字", "易误读词"]


def _distract(track, word, correct_mean):
    """生成 3 个干扰项: 同赛道/同族其他词义 (保持同类性)"""
    tr_meta = next((t for t in TRACKS if t[0] == track), None)
    lang = tr_meta[6] if tr_meta else "zh"
    fam = tr_meta[1] if tr_meta else ""
    pool = []
    if lang == "zh" and fam == "普通话":
        pool = [l for l in _PSC_LABELS if l != correct_mean]
    else:
        same_track = [m for w, m in _VOCAB.get(track, []) if w != word and m != correct_mean]
        random.shuffle(same_track)
        pool = same_track[:3]
    return pool[:3]


def _vocab_questions(track):
    """由词汇库生成词汇题 (按族定制题干)"""
    tr_meta = next((t for t in TRACKS if t[0] == track), None)
    fam = tr_meta[1] if tr_meta else ""
    if fam == "普通话":
        stem_tpl = "PSC字词判断:「{word}」属于哪一类?"
        expl_tpl = "{word} 属于{mean} — 普通话测试字词辨析考点。"
    elif fam == "中学语文":
        stem_tpl = "成语「{word}」的意思是?"
        expl_tpl = "{word} = {mean}。"
    elif fam == "HSK":
        stem_tpl = "HSK词汇:「{word}」的意思是?"
        expl_tpl = "{word} = {mean} ({track} 高频词)。"
    else:  # TOPIK
        stem_tpl = "TOPIK词汇:「{word}」的中文意思是?"
        expl_tpl = "{word} = {mean} ({track} 高频词)。"
    qs = []
    for word, mean in _VOCAB.get(track, []):
        opts = _distract(track, word, mean)
        opts.insert(random.randint(0, min(3, len(opts))), mean)
        qs.append((
            stem_tpl.format(word=word), opts[:4], opts.index(mean),
            expl_tpl.format(word=word, mean=mean, track=track),
            "词汇", random.randint(1, 3),
        ))
    return qs


def _all_items(track):
    """赛道全部基础题 = 考点题 + 词汇题"""
    return list(_KB.get(track, [])) + _vocab_questions(track)


